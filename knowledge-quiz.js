  function shuffle(items,rng){
    const out=items.slice(),random=typeof rng==='function'?rng:Math.random;
    for(let i=out.length-1;i>0;i--){let j=Math.floor(random()*(i+1));if(!Number.isFinite(j))j=0;j=Math.max(0,Math.min(i,j));[out[i],out[j]]=[out[j],out[i]];}
    return out;
  }
  function pickQuestions(count,rng){
    const limit=Math.max(1,Math.min(BANK.length,Math.floor(Number(count)||10)));
    return shuffle(BANK,rng).slice(0,limit).map(function(row){
      const opts=shuffle(row[3].map(function(text,index){return{text:text,originalIndex:index};}),rng);
      return{id:row[0],category:row[1],question:row[2],options:opts.map(function(o){return o.text;}),answerIndex:opts.findIndex(function(o){return o.originalIndex===row[4];})};
    });
  }
  function publicQuestions(questions){
    if(!Array.isArray(questions))return[];
    return questions.map(function(q){return{id:q.id,category:q.category,question:q.question,options:Array.isArray(q.options)?q.options.slice():[]};});
  }
  function sanitizePublicQuestions(value){
    if(!Array.isArray(value)||value.length!==10)return null;
    const safe=[];
    for(const q of value){
      if(!q||typeof q!=='object'||typeof q.id!=='string'||q.id.length>20||typeof q.question!=='string'||!q.question.trim()||q.question.length>300||typeof q.category!=='string'||q.category.length>60||!Array.isArray(q.options)||q.options.length!==4||!q.options.every(function(o){return typeof o==='string'&&o.length>0&&o.length<=120;}))return null;
      safe.push({id:q.id,category:q.category,question:q.question,options:q.options.slice()});
    }
    return new Set(safe.map(function(q){return q.id;})).size===10?safe:null;
  }
  function scoreAnswers(questions,answers){
    if(!Array.isArray(questions)||!questions.length||!Array.isArray(answers))return{correctCount:0,total:Array.isArray(questions)?questions.length:0,percent:0};
    const correctCount=questions.reduce(function(n,q,i){return n+(Number.isInteger(answers[i])&&answers[i]===q.answerIndex?1:0);},0);
    return{correctCount:correctCount,total:questions.length,percent:Math.round(correctCount*100/questions.length)};
  }
